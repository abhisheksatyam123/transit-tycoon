// Generates js/simulation/airportPositions.js from OpenTTD src/table/airport_movement.h (AirportMovingData).
// Usage: bun tools/gen-airport-positions.js <path to airport_movement.h> > js/simulation/airportPositions.js
// Per plane airport type: all nodes (x, y in 1/16 tile, relative to the airport origin; flags; comment name),
// the touchdown node (flag Land) and the holding nodes (comment "Fly around waiting for a landing spot").
import { readFileSync } from 'fs';
const src = readFileSync(process.argv[2], 'utf8').split('\n');
const TYPES = { country: 'small', commuter: 'commuter', city: 'city', metropolitan: 'metropolitan', international: 'international' };
function table(name) {
  const start = src.findIndex((l) => l.includes(`_airport_moving_data_${name}[`));
  const out = [];
  for (let i = start + 1; i < src.length && !src[i].startsWith('};'); i++) {
    const m = src[i].match(/\{\s*(-?\d+),\s*(-?\d+),\s*\{([^}]*)\}.*?\/\/\s*(\d+)\s+(.*)$/);
    if (!m) continue;
    const flags = (m[3].match(/AirportMovingDataFlag::(\w+)/g) || []).map((f) => f.split('::')[1]);
    out.push({ x: +m[1], y: +m[2], flags, idx: +m[4], name: m[5].trim() });
  }
  return out;
}
let js = '// Generated by tools/gen-airport-positions.js from OpenTTD src/table/airport_movement.h. Do not edit.\n';
js += '// Positions are OpenTTD AirportMovingData: x, y in 1/16 tile relative to the airport origin (x along the runway).\n';
js += 'export const OTTD_AIRPORT_NODES = {\n';
const info = [];
for (const [ottd, ours] of Object.entries(TYPES)) {
  const t = table(ottd);
  const land = t.find((p) => p.flags.includes('Land'));
  const hold = t.filter((p) => /Fly around waiting/.test(p.name));
  info.push(`  // ${ours} <- ${ottd}: touchdown node ${land.idx}, holding nodes ${hold.map((p) => p.idx).join(',')}`);
  js += `  ${ours}: {\n    landing: ${land.idx},\n    hold: [${hold.map((p) => p.idx).join(', ')}],\n    nodes: [\n`;
  js += t.map((p) => `      { x: ${p.x}, y: ${p.y}, flags: [${p.flags.map((f) => `'${f}'`).join(', ')}], name: ${JSON.stringify(p.name)} },`).join('\n');
  js += '\n    ],\n  },\n';
}
js += '};\n';
process.stderr.write(info.join('\n') + '\n');
process.stdout.write(js);
