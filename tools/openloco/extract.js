// Extracts OpenLoco track/road centreline geometry (MIT, https://github.com/OpenLoco/OpenLoco)
// into js/renderer/net/locoPieces.js. Run: bun tools/openloco/extract.js [--print]
// Each piece is stored in a canonical frame: start at origin, entry heading +x, units = tiles (32 world units).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OL = '/home/abhi/project/city_sim/scratchpad/openloco/src/OpenLoco/src/Map/Track/SubpositionData.cpp';
const out = join(root, 'js/renderer/net/locoPieces.js');
const src = readFileSync(OL, 'utf8');

// name -> points (world units, tile-local, 16 = centre)
const arrays = {};
for (const m of src.matchAll(/static constexpr auto (\w+) = std::to_array<MoveInfo>\(\s*\{([\s\S]*?)\}\s*\);/g)) {
  const pts = [...m[2].matchAll(/\{\s*\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\},\s*(\d+),\s*Pitch::\w+\s*\}/g)]
    .map((p) => [+p[1], +p[2]]);
  arrays[m[1]] = pts;
}

/** Canonical frame: origin = start point, +x = initial heading, tile units. */
function canon(pts) {
  const [x0, y0] = pts[0];
  let [dx, dy] = [pts[1][0] - x0, pts[1][1] - y0];
  const L = Math.hypot(dx, dy); const c = dx / L, s = dy / L;
  return pts.map(([x, y]) => {
    const rx = x - x0, ry = y - y0;
    return [+((rx * c + ry * s) / 32).toFixed(4), +((-rx * s + ry * c) / 32).toFixed(4)];
  });
}

/** Least-squares circle fit; returns { r, cx, cy }. */
function fitCircle(P) {
  let sx = 0, sy = 0, sxx = 0, syy = 0, sxy = 0, sz = 0, sxz = 0, syz = 0;
  const n = P.length;
  for (const [x, y] of P) { const z = x * x + y * y; sx += x; sy += y; sxx += x * x; syy += y * y; sxy += x * y; sz += z; sxz += x * z; syz += y * z; }
  // solve [sxx sxy sx; sxy syy sy; sx sy n] [A;B;C] = [-sxz; -syz; -sz] with circle x^2+y^2+Ax+By+C=0
  const M = [[sxx, sxy, sx, -sxz], [sxy, syy, sy, -syz], [sx, sy, n, -sz]];
  for (let i = 0; i < 3; i++) {
    let p = i; for (let k = i + 1; k < 3; k++) if (Math.abs(M[k][i]) > Math.abs(M[p][i])) p = k;
    [M[i], M[p]] = [M[p], M[i]];
    for (let k = 0; k < 3; k++) if (k !== i) { const f = M[k][i] / M[i][i]; for (let j = i; j < 4; j++) M[k][j] -= f * M[i][j]; }
  }
  const A = M[0][3] / M[0][0], B = M[1][3] / M[1][1], C = M[2][3] / M[2][2];
  const cx = -A / 2, cy = -B / 2;
  return { r: Math.sqrt(cx * cx + cy * cy - C), cx, cy };
}

function describe(name, pts) {
  const P = canon(pts);
  const last = P[P.length - 1];
  const end = P[P.length - 1], prev = P[P.length - 2];
  const endHeading = Math.atan2(end[1] - prev[1], end[0] - prev[0]);
  const len = P.slice(1).reduce((a, p, i) => a + Math.hypot(p[0] - P[i][0], p[1] - P[i][1]), 0);
  const turn = endHeading;
  const interior = P.slice(1, -1);
  const circ = interior.length >= 3 ? fitCircle(interior) : { r: Infinity };
  const rad = Number.isFinite(circ.r) && Math.abs(circ.r) < 50 ? Math.abs(circ.r) : Infinity;
  return { name, n: P.length, P, endX: last[0], endY: last[1], turnDeg: (turn * 180) / Math.PI, len, radius: rad };
}

const WANT = ['moveInfoT0R0D0', 'moveInfoT1R0D0', 'moveInfoT2R0D0', 'moveInfoT4R0D0', 'moveInfoT6R0D0', 'moveInfoT8R0D0',
  'moveInfoT9R0D0', 'moveInfoT10R0D0', 'moveInfoT11R0D0', 'moveInfoT12R0D0', 'moveInfoT13R0D0', 'moveInfoT14R0D0', 'moveInfoT16R0D0', 'moveInfoT18R0D0', 'moveInfoT19R0D0',
  'moveInfoT22R0D0', 'moveInfoT23R0D0', 'moveInfoT26R0D0', 'moveInfoT28R0D0', 'moveInfoT29R0D0', 'moveInfoT32R0D0', 'moveInfoT33R0D0',
  'moveInfoT34R0D0', 'moveInfoT35R0D0', 'moveInfoT38R0D0', 'moveInfoT39R0D0', 'moveInfoT42R0D0',
  'moveInfoTA0L0T0R0D0', 'moveInfoTA0L0T1R0D0', 'moveInfoTA0L0T3R0D0', 'moveInfoTA0L0T5R0D0', 'moveInfoTA0L0T7R0D0', 'moveInfoTA0L0T9R0D0'];

const pieces = WANT.filter((k) => arrays[k]).map((k) => describe(k.replace('moveInfo', ''), arrays[k]));

if (process.argv.includes('--print')) {
  console.log('name\tpts\tlen\tendX\tendY\tturnDeg\tradius');
  for (const p of pieces) console.log([p.name, p.n, p.len.toFixed(2), p.endX.toFixed(2), p.endY.toFixed(2), p.turnDeg.toFixed(1), p.radius.toFixed(2)].join('\t'));
}

const body = pieces.map((p) => `  { name: '${p.name}', len: ${p.len.toFixed(3)}, end: [${p.endX.toFixed(4)}, ${p.endY.toFixed(4)}], turnDeg: ${p.turnDeg.toFixed(2)}, radius: ${Number.isFinite(p.radius) ? p.radius.toFixed(3) : 'Infinity'}, pts: [${p.P.map((q) => `${q[0]},${q[1]}`).join(',')}] },`).join('\n');
writeFileSync(out, `/**
 * Ported from OpenLoco (MIT), https://github.com/OpenLoco/OpenLoco
 * Generated by tools/openloco/extract.js from src/Map/Track/SubpositionData.cpp (moveInfo* arrays).
 * Centreline geometry only (no graphics). Canonical frame: start (0,0), entry heading +x, units = tiles.
 * radius = least-squares circle fit of interior points (tiles); turnDeg = total heading change.
 */
export const LOCO_PIECES = [
${body}
];
`);
console.log('wrote', out, pieces.length, 'pieces');
