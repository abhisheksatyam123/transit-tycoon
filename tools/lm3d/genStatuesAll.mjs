// Regenerate tools/lm3d/ens/statuesAll.js from scratchpad/monuments.json (deduped OSM monument/artwork nodes).
import { writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOTS = JSON.parse(readFileSync('/home/abhi/project/city_sim/scratchpad/monuments.json', 'utf8'));

const idFor = (i, la, lo) => `r7d_osm_${i.toString(36)}_${Math.abs(Math.round((la * 1e6) | 0)).toString(36)}_${Math.abs(Math.round((lo * 1e6) | 0)).toString(36)}`;
const lines = [
  "/** Every remaining OSM monument/artwork on the Moscow map (scratchpad/monuments.json). Generated by tools/lm3d/genStatuesAll.js — do not edit by hand. */",
  "import { place } from '../model.js';",
  "import { genericStatueFaces } from './statueModels.js';",
  "",
  "const wrap = (id, la, lo, hd) => (toM) => place(genericStatueFaces(id), toM, la, lo, hd);",
  "",
  "export const STATUES_ALL = [",
];
for (let i = 0; i < DOTS.length; i++) {
  const [kind, la, lo, nm] = DOTS[i];
  const hd = Math.abs(((la * 37 + lo * 91) * 1000) | 0) % 360;
  const sid = idFor(i, la, lo);
  const tname = String(nm || 'Memorial').replace(/'/g, "\\'");
  lines.push(`  { id: '${sid}', title: 'OSM ${kind}: ${tname}', ground: 'none', streets: false, scale: 5, sel: { circle: [${la.toFixed(6)}, ${lo.toFixed(6)}, 3] }, anchor: [${la.toFixed(6)}, ${lo.toFixed(6)}], extraFaces: wrap('${sid}', ${la.toFixed(6)}, ${lo.toFixed(6)}, ${hd}) },`);
}
lines.push('];\n');
writeFileSync(join(root, 'tools/lm3d/ens/statuesAll.js'), lines.join('\n'));
console.log('wrote', join(root, 'tools/lm3d/ens/statuesAll.js'), DOTS.length, 'items');
