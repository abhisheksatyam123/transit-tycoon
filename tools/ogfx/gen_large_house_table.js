#!/usr/bin/env bun
/**
 * Generates js/renderer/pack/large_house_table.js from OpenTTD src/table/town_land.h (_original_house_specs,
 * _town_draw_tile_data, GPL-2.0): the temperate multi-tile houses (Size1x2 and Size2x2). A multi-tile house is a
 * group of consecutive house ids: a 2x2 spec S has parts S..S+3 at offsets (0,0),(0,1),(1,0),(1,1) (dx = p>>1,
 * dy = p&1, as GetHouseNorthPart in town_cmd.cpp); a 1x2 spec S has parts S, S+1 at (0,0),(0,1).
 * Each part has stage-3 [ground, building, dx, dy] per TileHash2Bit. Groups whose sprites are missing from the
 * OpenGFX temperate manifest are skipped.
 * Usage: bun tools/ogfx/gen_large_house_table.js [--ottd <openttd src dir>]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const OTTD = resolve(args.includes('--ottd') ? args[args.indexOf('--ottd') + 1] : join(here, '../../../scratchpad/openttd/src'));
const OUT = resolve(join(here, '../../js/renderer/pack/large_house_table.js'));
const MANIFEST = resolve(join(here, '../../assets/opengfx/manifest.json'));
const th = readFileSync(join(OTTD, 'table/town_land.h'), 'utf8');
const sp = readFileSync(join(OTTD, 'table/sprites.h'), 'utf8');
const have = new Set(Object.keys(JSON.parse(readFileSync(MANIFEST, 'utf8')).sprites).map(Number));
const names = new Map();
for (const m of sp.matchAll(/SpriteID\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;/g)) names.set(m[1], Number(m[2]));
const val = (t) => {
  t = t.trim();
  if (/^0x/.test(t)) return parseInt(t, 16);
  if (/^\d+$/.test(t)) return +t;
  if (!names.has(t)) throw new Error(`unknown sprite ${t}`);
  return names.get(t);
};
const a = th.indexOf('_town_draw_tile_data[] = {');
const draws = th.slice(a, th.indexOf('\n};', a)).split('\n').filter((l) => /^\tM\(/.test(l)).map((l) => {
  const f = l.slice(l.indexOf('(') + 1, l.lastIndexOf(')')).split(',').map((s) => s.trim());
  return { s1: val(f[0]), s2: val(f[2]), dx: +f[4], dy: +f[5] };
});
const c = th.indexOf('_original_house_specs[] = {');
const body = th.slice(c, th.indexOf('static_assert(lengthof(_original_house_specs)', c));
const specs = body.split(/\n\tMS\(/).slice(1).map((p, id) => {
  const zi = p.indexOf('HouseZones');
  const zones = zi < 0 ? [] : p.slice(zi, p.indexOf('})', zi)).replace(/HouseZone::/g, '').replace(/HouseZones\(\{/, '').split(',').map((s) => s.trim());
  const m = /MS\(\s*(\d+),\s*[^,]+,\s*(\d+),/.exec('MS(' + p);
  const sz = (p.match(/Size(\dx\d)/) || [])[1] || null;
  return { id, zones, minYear: +m[1], pop: +m[2], size: sz };
});
const partPairs = (id) => [0, 1, 2, 3].map((v) => {
  const d = draws[id * 16 + v * 4 + 3];
  return [d.s1, d.s2, d.dx, d.dy];
});
// OpenTTD HouseZone climates -> our climate tags (largeHouses.js LARGE_GROUPS.climates)
const CLIMATE_TAGS = [['ClimateTemperate', 'temperate'], ['ClimateSubarcticBelowSnow', 'arctic-below'],
  ['ClimateSubarcticAboveSnow', 'arctic-above'], ['ClimateSubtropic', 'tropic']];
const groups = [];
for (const s of specs) {
  if (s.size !== '2x2' && s.size !== '1x2') continue;
  const climates = CLIMATE_TAGS.filter(([z]) => s.zones.includes(z)).map(([, tag]) => tag);
  if (!climates.length) continue;
  const n = s.size === '2x2' ? 4 : 2;
  const parts = [];
  for (let p = 0; p < n; p++) {
    const id = s.id + p;
    const offs = s.size === '2x2' ? [p >> 1, p & 1] : [0, p];
    const pairs = partPairs(id);
    parts.push({ id, offs, pairs });
  }
  // building 0 = ground-only part (OpenTTD spec 40 part 3 draws no building sprite)
  const ok = parts.every((q) => q.pairs.every(([g, b]) => have.has(g) && (b === 0 || have.has(b))));
  if (!ok) { console.error(`skip ${s.id} ${s.size}: sprites missing`); continue; }
  groups.push({ id: s.id, size: s.size, minYear: s.minYear, pop: s.pop, climates, parts });
}
const lines = [];
lines.push(`// Generated by tools/ogfx/gen_large_house_table.js from OpenTTD src/table/town_land.h (_original_house_specs,`);
lines.push(`// _town_draw_tile_data; GPL-2.0). Multi-tile houses of the temperate, sub-arctic and sub-tropic climates (Size2x2 / Size1x2). Each house id is one part:`);
lines.push(`// LARGE_HOUSES[id] = { group, part, size, dx, dy (tile offset of the part), pairs[TileHash2Bit] = [ground, building, dx, dy] }.`);
lines.push(`// Sprite ids are OpenGFX base sprite ids (never renumber: append new groups only).`);
lines.push('');
lines.push('/** Part house id -> part data (see header). */');
lines.push('export const LARGE_HOUSES = {');
for (const g of groups) {
  for (const q of g.parts) {
    const pr = q.pairs.map((p) => `[${p.join(', ')}]`).join(', ');
    lines.push(`  ${q.id}: { group: ${g.id}, size: '${g.size}', part: ${q.id - g.id}, dx: ${q.offs[0]}, dy: ${q.offs[1]}, pairs: [${pr}] },`);
  }
}
lines.push('};');
lines.push('');
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${groups.length} groups, ${groups.reduce((n, g) => n + g.parts.length, 0)} parts`);
