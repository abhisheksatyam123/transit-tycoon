#!/usr/bin/env bun
/**
 * Generates js/renderer/pack/tropic_house_table.js from OpenTTD src/table/town_land.h (_original_house_specs,
 * _town_draw_tile_data, GPL-2.0): the sub-tropical (HouseZone::ClimateSubtropic) 1x1 houses. Stage-3 [ground,
 * building, dx, dy] per TileHash2Bit, plus min year and population. Desert and rainforest share this zone in OpenTTD.
 * Usage: bun tools/ogfx/gen_tropic_house_table.js --ottd <openttd src dir>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const OTTD = resolve(args.includes('--ottd') ? args[args.indexOf('--ottd') + 1] : join(here, '../../../scratchpad/openttd/src'));
const OUT = resolve(join(here, '../../js/renderer/pack/tropic_house_table.js'));
const th = readFileSync(join(OTTD, 'table/town_land.h'), 'utf8');
const sp = readFileSync(join(OTTD, 'table/sprites.h'), 'utf8');
const names = new Map();
for (const m of sp.matchAll(/SpriteID\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;/g)) names.set(m[1], Number(m[2]));
const val = (t) => {
  t = t.trim();
  if (/^0x/.test(t)) return parseInt(t, 16);
  if (/^\d+$/.test(t)) return +t;
  if (!names.has(t)) throw new Error(`unknown sprite ${t}`);
  return names.get(t);
};
const a = th.indexOf('_town_draw_tile_data[] = {');
const draws = th.slice(a, th.indexOf('\n};', a)).split('\n').filter((l) => /^\tM\(/.test(l)).map((l) => {
  const f = l.slice(l.indexOf('(') + 1, l.lastIndexOf(')')).split(',').map((s) => s.trim());
  return { s1: val(f[0]), s2: val(f[2]), dx: +f[4], dy: +f[5] };
});
const c = th.indexOf('_original_house_specs[] = {');
const body = th.slice(c, th.indexOf('static_assert(lengthof(_original_house_specs)', c));
const specs = body.split(/\n\tMS\(/).slice(1).map((p, id) => {
  const zm = /HouseZones\(\{([^}]*)\}\)/.exec(p);
  const zones = zm ? zm[1].replace(/HouseZone::/g, '').split(',').map((s) => s.trim()) : [];
  const m = /MS\(\s*(\d+),\s*[^,]+,\s*(\d+),/.exec('MS(' + p);
  return { id, zones, minYear: +m[1], pop: +m[2], size1: /Size1x1/.test(p) };
});
const out = [];
for (const s of specs) {
  if (!s.zones.includes('ClimateSubtropic') || !s.size1) continue;
  const pairs = [0, 1, 2, 3].map((v) => {
    const d = draws[s.id * 16 + v * 4 + 3];
    return [d.s1, d.s2, d.dx, d.dy];
  });
  out.push({ id: s.id, minYear: s.minYear, pop: s.pop, pairs });
}
const lines = out.map((h) => `  { id: ${h.id}, minYear: ${h.minYear}, pop: ${h.pop}, pairs: [${h.pairs.map((p) => `[${p.join(', ')}]`).join(', ')}] },`);
writeFileSync(OUT, `// Generated by tools/ogfx/gen_tropic_house_table.js from OpenTTD src/table/town_land.h (_original_house_specs,
// _town_draw_tile_data; GPL-2.0). Sub-tropical (ClimateSubtropic) 1x1 houses: OpenTTD house id, min year, population,
// stage-3 [ground, building, dx, dy] per TileHash2Bit. Ids are OpenGFX base/tropical sprite ids (see extract_tropic.js).
export const TROPIC_HOUSES = [
${lines.join('\n')}
];
`);
console.log(`tropic houses ${out.length} -> ${OUT}`);
