/**
 * Round AC industry settings (default-preserving ports of OpenTTD industry_cmd.cpp):
 *  - industryAbandonment : secondary industries idle PROCESSING_INDUSTRY_ABANDONMENT_YEARS close at Chance16(1,180)/month
 *  - protectLastIndustry : the last instance of an industry type cannot close (CheckIndustryCloseDownProtection)
 * Defaults are false and reproduce the current Transit Tycoon behaviour (no abandonment, last instance may close).
 * The behaviour tests use a seeded game and a fixed number of monthly updates; the forced-draw tests use a stub RNG
 * that always returns the lowest value so the closure draw succeeds deterministically.
 */
import { describe, expect, test } from 'bun:test';
import { flatGame } from './helpers.js';
import { DEFAULT_SETTINGS, setSetting } from '../js/simulation/settings.js';
import { SETTING_META } from '../js/ui/settingsGroups.js';
import { placeIndustry } from '../js/simulation/industries.js';
import * as Industry from '../js/simulation/loco/industry.js';

const KEYS = ['industryAbandonment', 'protectLastIndustry'];

/** Sawmill (secondary: accepts WOOD, no input delivered = no production) placed on the flat test area. */
function idleSawmill(game, x = 20, y = 20) {
  const s = game.state;
  // Only this test's sawmills exist: drop any generated by the town/industry setup so instance counts are exact.
  s.industries = s.industries.filter((i) => i.typeId !== 'sawmill');
  const ind = placeIndustry(s, 'sawmill', x, y);
  ind.foundingYear = s.date.year - 6; // idle for 6 years (OpenTTD last_prod_year)
  return ind;
}

/** Game wrapper whose RNG always returns the lowest value, so every Chance draw succeeds. */
function forcedGame(game) {
  return { state: game.state, rng: { int: (lo) => lo } };
}

describe('Round AC industry settings: defaults', () => {
  test('defaults are false', () => {
    for (const k of KEYS) expect(DEFAULT_SETTINGS[k]).toBe(false);
  });

  test('each key has exactly one SETTING_META entry in the economy group', () => {
    for (const k of KEYS) {
      const entries = SETTING_META.filter((m) => m.key === k);
      expect(entries.length).toBe(1);
      expect(entries[0].group).toBe('economy');
      expect(typeof entries[0].label).toBe('string');
      expect(entries[0].type).toBe('check');
      expect(typeof entries[0].help).toBe('string');
    }
  });
});

describe('industryAbandonment', () => {
  test('default: idle secondary does not close over many months', () => {
    const game = flatGame(7);
    const ind = idleSawmill(game);
    for (let m = 0; m < 2000; m++) Industry.updateMonthly(game, ind);
    expect(ind.closingDown).toBe(false);
    expect(game.state.industries).toContain(ind);
  });

  test('on: idle secondary closes within 2000 months (seed 7, fixed RNG sequence)', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    const ind = idleSawmill(game);
    let closedAt = -1;
    for (let m = 0; m < 2000 && closedAt < 0; m++) {
      Industry.updateMonthly(game, ind);
      if (ind.closingDown) closedAt = m;
    }
    expect(closedAt).toBeGreaterThanOrEqual(0);
    expect(closedAt).toBeLessThan(2000);
  });

  test('on: primary industries are not abandoned by this rule', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    const ind = placeIndustry(game.state, 'forest', 20, 20);
    ind.foundingYear = game.state.date.year - 10;
    expect(Industry.isMonthlyAbandonment({ int: (lo) => lo }, game.state, ind)).toBe(false);
  });

  test('on: a recent production month resets the idle clock', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    const ind = idleSawmill(game);
    ind.producedMonthly = [1, 0];
    Industry.updateMonthly(game, ind);
    expect(ind.lastProductionYear).toBe(game.state.date.year);
    expect(Industry.isMonthlyAbandonment({ int: (lo) => lo }, game.state, ind)).toBe(false);
  });
});

describe('protectLastIndustry', () => {
  test('default: last instance of a type closes when its closure draw succeeds', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    const ind = idleSawmill(game);
    Industry.updateMonthly(forcedGame(game), ind);
    expect(ind.closingDown).toBe(true);
  });

  test('on: last instance is not closed even when its closure draw succeeds', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    setSetting(game.state, 'protectLastIndustry', true);
    const ind = idleSawmill(game);
    for (let m = 0; m < 50; m++) Industry.updateMonthly(forcedGame(game), ind);
    expect(ind.closingDown).toBe(false);
    expect(game.state.industries).toContain(ind);
  });

  test('on: with two instances of the type, closure is not blocked (protection covers only the last one)', () => {
    const game = flatGame(7);
    setSetting(game.state, 'industryAbandonment', true);
    setSetting(game.state, 'protectLastIndustry', true);
    const a = idleSawmill(game, 20, 20);
    const b = placeIndustry(game.state, 'sawmill', 30, 20);
    b.foundingYear = game.state.date.year - 6;
    Industry.updateMonthly(forcedGame(game), a);
    expect(a.closingDown).toBe(true);
    Industry.updateMonthly(forcedGame(game), b);
    expect(b.closingDown).toBe(true);
  });
});
